'use client';

import React, { useState } from 'react';
import { useRouter } from 'next/navigation';
import {
  Tag,
  Save,
  Loader2,
  ChevronDown,
} from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { useCreateProductCategoryMutation } from '@/service/api/superAdminService';

export function ProductCategoryCreateScreen() {
  const router = useRouter();
  const [createCategory, { isLoading }] = useCreateProductCategoryMutation();

  const [form, setForm] = useState<{
    Category_Name: string;
    Is_Active: boolean;
    Description: string;
  }>({
    Category_Name: '',
    Is_Active: true,
    Description: '',
  });

  const handleSave = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!form.Category_Name?.trim()) {
      toast.error('Product Category name is required.');
      return;
    }

    // STRICT CREATE PAYLOAD: Category_Id and Category_Code are autogenerated by backend, DO NOT send them
    const payload = {
      Organization_Id: 1,
      Category_Name: form.Category_Name.trim(),
      Description: form.Description?.trim() || '',
      Is_Active: Boolean(form.Is_Active),
      Is_Deleted: false,
      Created_By: 1,
      Updated_By: 1,
    };

    try {
      await createCategory(payload).unwrap();
      toast.success(`Product Category "${payload.Category_Name}" created successfully!`);
      router.push('/products/category');
    } catch (err: any) {
      console.error('Failed to create category:', err);
      toast.error(err?.data?.Error || 'Failed to create product category.');
    }
  };

  return (
    <div className="w-full space-y-6 pb-14 font-sans text-slate-800 antialiased max-w-3xl mx-auto">
      {/* 1. BREADCRUMBS & TOP BAR */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-4">
        <div>
          <div className="flex items-center gap-2 text-xs font-medium text-slate-500 mb-1">
            <span
              className="hover:text-slate-800 cursor-pointer"
              onClick={() => router.push('/products/category')}
            >
              Product Management
            </span>
            <span className="text-slate-400">&gt;</span>
            <span
              className="hover:text-slate-800 cursor-pointer"
              onClick={() => router.push('/products/category')}
            >
              Product Category
            </span>
            <span className="text-slate-400">&gt;</span>
            <span className="text-slate-800 font-semibold">Create Category</span>
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900">
            Create Product Category
          </h1>
        </div>

        <div className="flex items-center gap-2.5 self-start sm:self-auto">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => router.push('/products/category')}
            className="h-9 px-4 text-xs font-semibold border-slate-300 text-slate-700 hover:bg-slate-50"
          >
            Cancel
          </Button>
          <Button
            type="button"
            onClick={handleSave}
            disabled={isLoading}
            className="h-9 px-5 bg-[#6222cc] hover:bg-[#521cb0] text-white text-xs font-semibold shadow-xs flex items-center gap-1.5 cursor-pointer"
          >
            {isLoading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Save className="h-4 w-4" />}
            <span>Save Category</span>
          </Button>
        </div>
      </div>

      {/* FORM CARD WITH VISIBLE BORDER */}
      <form onSubmit={handleSave} className="space-y-6">
        <div className="bg-white rounded-2xl border-2 border-slate-300 p-6 shadow-sm space-y-5">
          <div className="flex items-center gap-2.5 font-bold text-slate-900 text-sm border-b border-slate-200 pb-3">
            <span className="p-1.5 rounded-lg bg-purple-50 text-[#6222cc]">
              <Tag className="h-4 w-4" />
            </span>
            <span>Category Information</span>
          </div>

          {/* ONLY Category ID, Product Category, Status, Description */}
          <div className="space-y-4 text-xs">
            {/* Field 1: Category ID (clean label, autogeneration note removed, disabled) */}
            <div className="space-y-1.5">
              <label className="font-semibold text-slate-700">Category ID</label>
              <Input
                readOnly
                disabled
                value="Auto-generated by system upon save"
                className="h-9 font-mono text-xs bg-slate-100 text-slate-500 border-slate-300 rounded-lg cursor-not-allowed select-none font-semibold"
              />
            </div>

            {/* Field 2: Product Category (Category Name) */}
            <div className="space-y-1.5">
              <label className="font-semibold text-slate-700">
                Product Category <span className="text-red-500">*</span>
              </label>
              <Input
                placeholder="e.g. CRM, Education ERP, HRMS"
                value={form.Category_Name}
                onChange={(e) => setForm({ ...form, Category_Name: e.target.value })}
                className="h-9 text-xs font-medium border-slate-300 rounded-lg"
                required
              />
            </div>

            {/* Field 3: Status */}
            <div className="space-y-1.5">
              <label className="font-semibold text-slate-700">Status</label>
              <div className="relative">
                <select
                  value={form.Is_Active ? 'Active' : 'Inactive'}
                  onChange={(e) => setForm({ ...form, Is_Active: e.target.value === 'Active' })}
                  className="w-full h-9 pl-3 pr-8 text-xs bg-white border border-slate-300 rounded-lg text-slate-800 font-medium outline-none focus:ring-1 focus:ring-[#6222cc] cursor-pointer appearance-none"
                >
                  <option value="Active">Active</option>
                  <option value="Inactive">Inactive</option>
                </select>
                <ChevronDown className="h-3.5 w-3.5 text-slate-400 absolute right-2.5 top-1/2 -translate-y-1/2 pointer-events-none" />
              </div>
            </div>

            {/* Field 4: Description */}
            <div className="space-y-1.5">
              <label className="font-semibold text-slate-700">Description</label>
              <Textarea
                rows={4}
                placeholder="Category details and description..."
                value={form.Description}
                onChange={(e) => setForm({ ...form, Description: e.target.value })}
                className="text-xs resize-none border-slate-300 rounded-lg"
              />
            </div>
          </div>
        </div>

        <div className="flex justify-end gap-2.5">
          <Button
            type="button"
            variant="outline"
            onClick={() => router.push('/products/category')}
            className="text-xs border-slate-300"
          >
            Cancel
          </Button>
          <Button
            type="submit"
            disabled={isLoading}
            className="bg-[#6222cc] hover:bg-[#521cb0] text-white text-xs px-5 flex items-center gap-1.5 cursor-pointer"
          >
            {isLoading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Save className="h-4 w-4" />}
            Save Category
          </Button>
        </div>
      </form>
    </div>
  );
}
